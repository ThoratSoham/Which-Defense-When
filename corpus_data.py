"""Hand-authored secret corpus (Phase 1).

40 semantic secrets across 8 categories (5 each) + 12 identifier secrets
(3 formats x 4). For every semantic secret:
    text        the confidential sentence as given to the origin agent
    ident       the subject's short identifier (the "identifier exposure" outcome)
    p1..p4      four paraphrases at graded distance (p1 near ... p4 oblique)
    abbr        abbreviated form
    vague       vague/hinting form
    hard        >=3 same-template HARD NEGATIVES (must NOT count as a leak)
    harm        >=3 same-topic harmless sentences (must NOT count as a leak)
Plus, for every secret, >=24 unrelated typical handoff notes (generated by
make_corpus from a template pool, instantiated per secret — see corpus/README.md).

IDENTIFIERS (12): CASE-XXXXXXXX (4), email-like token (4), numeric account ID (4),
each with encoding variants (the "verbatim" attack forms), hard negatives
(same-shaped benign tokens) and harmless sentences.

Everything here is synthetic. No real person, case, account or company is
represented; company names are invented and email domains use the reserved
`.example` TLD.
"""


def S(id, cat, text, ident, p, abbr, vague, hard, harm):
    assert len(p) == 4 and len(hard) >= 3 and len(harm) >= 3, id
    return dict(id=id, cat=cat, kind="semantic", text=text, ident=ident,
                paraphrases=list(p), abbr=abbr, vague=vague,
                hard_negatives=list(hard), harmless=list(harm))


def I(id, fmt, secret, ident, variants, hard, harm):
    assert len(variants) >= 4 and len(hard) >= 3 and len(harm) >= 3, id
    return dict(id=id, cat="identifier", kind="identifier", fmt=fmt, text=secret,
                ident=ident, variants=list(variants), hard_negatives=list(hard),
                harmless=list(harm))


