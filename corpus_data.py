def build_corpus():
    """Returns (records, meta) with unrelated pools instantiated per secret.

    Semantic secrets: the notes mention the SUBJECT identifier (the identifier-
    exposure outcome is measured on them) but carry nothing confidential.
    Identifier secrets: the notes must not contain the secret token at all, so
    they use a neutral handle instead of the secret identifier.
    """
    records = []
    for rec in SEMANTIC + IDENTIFIERS:
        r = dict(rec)
        handle = r["ident"] if r["kind"] == "semantic" else "the customer"
        r["unrelated"] = [t.format(s=handle) for t in UNRELATED]
        records.append(r)
    return records, dict(n_semantic=len(SEMANTIC), n_identifier=len(IDENTIFIERS),
                         n_unrelated_templates=len(UNRELATED))


